"""Generate static/css/ax-tokens.css from design/figma-tokens.json.

figma-tokens.json is the single source for colours, type, spacing, radius, sizes and
shadows (DESIGN.md 3). Run this after editing the tokens; tests/test_shell.py fails
if the CSS is out of date.

Usage:  .venv/bin/python scripts/build_tokens.py [--check]
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'design' / 'figma-tokens.json'
OUT = ROOT / 'static' / 'css' / 'ax-tokens.css'


def _lookup(tokens: dict, path: str):
    node = tokens
    for part in path.split('.'):
        node = node[part]
    return node['$value'] if isinstance(node, dict) and '$value' in node else node


def resolve(tokens: dict, value):
    if isinstance(value, str):
        m = re.fullmatch(r'\{([^}]+)\}', value)
        if m:
            return resolve(tokens, _lookup(tokens, m.group(1)))
    return value


def _hex_alpha(color: str) -> str:
    """#RRGGBBAA -> rgba(); other colours unchanged."""
    if re.fullmatch(r'#[0-9a-fA-F]{8}', color):
        r, g, b, a = (int(color[i:i + 2], 16) for i in (1, 3, 5, 7))
        return f"rgba({r}, {g}, {b}, {round(a / 255, 3)})"
    return color


def _shadow(v) -> str:
    items = v if isinstance(v, list) else [v]
    return ', '.join(f"{s['offsetX']} {s['offsetY']} {s['blur']} {s['spread']} {_hex_alpha(s['color'])}" for s in items)


def build(tokens: dict) -> str:
    def colors(group: str) -> list[str]:
        return [f"  --{k}: {resolve(tokens, v['$value'])};" for k, v in tokens[group].items() if not k.startswith('$')]

    family = ', '.join(f'"{f}"' if ' ' in f else f for f in tokens['font']['family']['$value'])
    lines = [
        '/* Generated by scripts/build_tokens.py from design/figma-tokens.json. Do not edit by hand. */',
        '',
        ':root {',
        *[f"  --{k}: {v['$value']};" for k, v in tokens['brand'].items()],
        *colors('light'),
        '  --magenta-soft: var(--accent-soft);',
    ]
    for name, st in tokens['status'].items():
        lines.append(f"  --status-{name}-bg: {resolve(tokens, st['bg']['$value'])};")
        lines.append(f"  --status-{name}-fg: {resolve(tokens, st['fg']['$value'])};")
    lines.append(f"  --font-family: {family};")
    for k in ('weight-regular', 'weight-bold'):
        lines.append(f"  --font-{k}: {tokens['font'][k]['$value']};")
    for name, t in tokens['type'].items():
        v = t['$value']
        lines.append(f"  --type-{name}-size: {v['fontSize']};")
        lines.append(f"  --type-{name}-weight: {v['fontWeight']};")
        lines.append(f"  --type-{name}-line: {v['lineHeight']};")
    lines += [f"  --space-{k}: {v['$value']};" for k, v in tokens['space'].items()]
    lines += [f"  --radius-{k}: {v['$value']};" for k, v in tokens['radius'].items()]
    lines += [f"  --{k}: {v['$value']};" for k, v in tokens['size'].items()]
    lines.append(f"  --shadow-pop: {_shadow(tokens['shadow']['pop']['$value'])};")
    lines.append(f"  --focus-ring: {_shadow(tokens['shadow']['focus-ring']['$value'])};")
    lines += [f"  --threshold-{k}: {v['$value']};" for k, v in tokens['threshold'].items()]
    lines += ['  color-scheme: light;', '}', '']

    dark = colors('dark') + ['  --magenta-soft: var(--accent-soft);', '  color-scheme: dark;']
    lines += ['@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {',
              *['  ' + l for l in dark], '  }', '}', '', ':root[data-theme="dark"] {', *dark, '}', '']
    return '\n'.join(lines)


def main():
    css = build(json.loads(SRC.read_text(encoding='utf-8')))
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != css:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date. Run scripts/build_tokens.py.")
        print('Tokens up to date.')
        return
    OUT.write_text(css, encoding='utf-8')
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == '__main__':
    main()
